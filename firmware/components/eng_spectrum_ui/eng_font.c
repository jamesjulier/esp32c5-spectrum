const uint8_t *eng_font_glyph(char c)
{
    for (size_t i = 0; i < sizeof GLYPHS / sizeof GLYPHS[0]; i++)
        if (GLYPHS[i].c == c) return GLYPHS[i].rows;
    return NULL;
}

int eng_font_width(const char *s, int scale)
{
    int n = (int)strlen(s);
    return n ? (n * 6 - 1) * scale : 0;
}
