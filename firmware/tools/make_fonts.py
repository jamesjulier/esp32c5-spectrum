"""
Anti-aliased fonts for the spectrum screen on the 2.8" board, as C tables
(components/eng_spectrum_ui/eng_font_aa.c). This firmware has no graphics
library, so eng_font_aa.c carries each glyph's 8-bit coverage and eng_text()
blends it onto the strip being drawn.

Manrope Bold for the band name, Inter for the rest. Both are SIL OFL 1.1,
which allows embedding them in this program (see FONTS-LICENCE.md). They
replace the 5x7 bitmap font, which read as blocky on the 2.8" screen.

Usage:  python3 tools/make_fonts.py [INTER_TTF] [MANROPE_TTF]
Regenerating from the same font files reproduces eng_font_aa.c exactly.
"""
import os
import sys

import freetype

HOME = os.path.expanduser("~")
INTER = sys.argv[1] if len(sys.argv) > 1 else f"{HOME}/Library/Fonts/Inter-VariableFont_opsz,wght.ttf"
MANROPE = sys.argv[2] if len(sys.argv) > 2 else f"{HOME}/Library/Fonts/Manrope-VariableFont_wght.ttf"

# Printable ASCII, then the middle dot (glyph 95) and the em dash for "not
# measured" (glyph 96); eng_text() maps U+00B7 and U+2014 to them.
CHARS = [chr(c) for c in range(0x20, 0x7F)] + ["\u00b7", "\u2014"]

# C name, file, pixel size, weight
FONTS = [
    ("eng_font_title", MANROPE, 18, 700),   # band name
    ("eng_font_text",  INTER,   13, 500),   # header lines, readout, scorecard
    ("eng_font_label", INTER,   11, 500),   # dB labels, channel numbers
]


def set_weight(face, weight):
    try:
        info = face.get_variation_info()
    except Exception:
        return
    face.set_var_design_coords([weight if a.tag == "wght" else a.default for a in info.axes])


def font_c(name, path, size, weight):
    face = freetype.Face(path)
    set_weight(face, weight)
    face.set_pixel_sizes(0, size)
    glyphs, data = [], bytearray()
    for ch in CHARS:
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g, bm = face.glyph, face.glyph.bitmap
        glyphs.append((bm.width, bm.rows, g.bitmap_left, g.bitmap_top, g.advance.x >> 6, len(data)))
        data += bytes(bm.buffer[:bm.width * bm.rows])
    asc = face.size.ascender >> 6
    out = [f"// {os.path.basename(path)} {size}px weight {weight}",
           f"static const uint8_t {name}_px[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const eng_glyph_t {name}_g[{len(glyphs)}] = {{")
    for w, h, l, t, a, o in glyphs:
        out.append(f"    {{{w},{h},{l},{t},{a},{o}}},")
    out.append("};")
    out.append(f"const eng_aa_font_t {name} = {{ {name}_g, {name}_px, {asc}, {size} }};")
    return "\n".join(out)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, "..", "components", "eng_spectrum_ui", "eng_font_aa.c")
    parts = ["// SPDX-License-Identifier: GPL-3.0-or-later",
             "// GENERATED by tools/make_fonts.py. Do not edit. Fonts: Inter and Manrope, SIL OFL 1.1.",
             '#include "eng_font_aa.h"', ""]
    parts += [font_c(*f) + "\n" for f in FONTS]
    with open(os.path.normpath(dst), "w") as f:
        f.write("\n".join(parts))
    print(os.path.normpath(dst), os.path.getsize(dst), "bytes of C")


if __name__ == "__main__":
    main()
